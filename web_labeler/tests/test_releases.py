PROD_MAP = """# AUTO-GENERATED by mapping/generate_reconcile_map.py

CASA VINA OLD:
- glasses.CASA

Casa Vina:
- glasses.CASA

Niska:
- glasses.NISKA_BELO_ZUTO
- shots.RED

"Rakija: Dunja":
- shots.AMBER
"""


class ReleaseTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        t = self.tmp = Path(self._tmp.name)
        for d in ("Models", "pos", "training", "documented", "live/glasses", "live/shots", "prod"):
            (t / d).mkdir(parents=True)
        (t / "Models" / "Glasses.yaml").write_text("names: [CASA, NISKA_BELO, NISKA_ZUTO, LEGACY_OLD]\n", encoding="utf-8")
        (t / "Models" / "Shots.yaml").write_text("names: [RED, AMBER]\n", encoding="utf-8")
        self.write_live("glasses", ["CASA", "NISKA_BELO_ZUTO", "background"])
        self.write_live("shots", ["RED", "AMBER"])
        (t / "training" / "glasses.yaml").write_text(yaml.safe_dump({"roi_crop": True, "classes": {
            "exclude": [], "exclude_prefixes": ["LEGACY_"],
            "unite": [{"classes": ["NISKA_BELO", "NISKA_ZUTO"], "as": "NISKA_BELO_ZUTO"}]}}), encoding="utf-8")
        (t / "training" / "shots.yaml").write_text(yaml.safe_dump({"classes": {"exclude": []}}), encoding="utf-8")
        (t / "documented" / "glasses.yaml").write_text(yaml.safe_dump({
            "model": "glasses", "status": "DRAFT", "classes": ["CASA", "NISKA_BELO", "NISKA_ZUTO", "LEGACY_OLD"],
            "excluded": [{"class": "LEGACY_OLD", "reason": "staro"}],
            "unite": [{"into": "NISKA_BELO_ZUTO", "classes": ["NISKA_BELO", "NISKA_ZUTO"], "reason": "x"}]}), encoding="utf-8")
        (t / "documented" / "shots.yaml").write_text(yaml.safe_dump({
            "model": "shots", "classes": ["RED", "AMBER"], "excluded": [], "unite": []}), encoding="utf-8")
        self.write_map()
        (t / "prod" / "blacklist_items.txt").write_text("# hrana\nOMLET\nSkip Me\n# TOC STARO\n", encoding="utf-8")
        (t / "prod" / "pos_to_internal_mapping.yaml").write_text(PROD_MAP, encoding="utf-8")
        with open(t / "pos" / "a.csv", "w", encoding="utf-8", newline="") as f:
            csv.writer(f).writerows([
                pos_row("0100", "Casa Vina", "2026.11.20 10:00"), pos_row("0200", "Niska", "2026.11.20 10:30"),
                pos_row("0300", "OMLET", "2026.11.20 11:00"), pos_row("0400", "NEW DRINK", "2026.11.20 11:30"),
                pos_row("0500", "Rakija: Dunja", "2026.11.20 12:00")])
        self.settings = self.make_settings()
        catalog.import_catalog(self.settings)

    def tearDown(self):
        for p in self.tmp.rglob("*"):
            if p.is_dir():
                p.chmod(0o755)
        self._tmp.cleanup()

    def write_live(self, model, names):
        (self.tmp / "live" / model / "active_classes.yaml").write_text(yaml.safe_dump({"names": names}), encoding="utf-8")

    def write_map(self, drop=None):
        articles = [
            {"pos_name": "Casa Vina", "aliases": ["CASA VINA OLD"], "status": "incl",
             "mappings": [{"model": "glasses", "class": "CASA", "priority": 1}]},
            {"pos_name": "Rakija: Dunja", "status": "incl", "mappings": [{"model": "shots", "class": "AMBER"}]},
            {"pos_name": "Niska", "status": "incl", "mapping_mode": "fallback",
             "mappings": [{"model": "glasses", "class": "NISKA_BELO_ZUTO"}, {"model": "shots", "class": "RED"}]},
            {"pos_name": "Skip Me", "status": "skip", "mappings": []},
            {"pos_name": "Miss No Class", "status": "miss", "mappings": []},
        ]
        articles = [a for a in articles if a["pos_name"] != drop]
        (self.tmp / "map.yaml").write_text(yaml.safe_dump({"articles": articles}, allow_unicode=True), encoding="utf-8")

    def make_settings(self, **extra):
        t = self.tmp
        cfg = {"catalog_venue_id": "venue_a", "catalog_db_path": str(t / "db" / "catalog.db"),
               "catalog_pos_dir": str(t / "pos"), "catalog_pos_adapter": "blaznavac_csv",
               "article_map_path": str(t / "map.yaml"), "catalog_blacklist_path": str(t / "prod" / "blacklist_items.txt"),
               "catalog_pipeline_map_path": str(t / "prod" / "pos_to_internal_mapping.yaml"),
               "catalog_training_config_dir": str(t / "training"), "catalog_documented_classes_dir": str(t / "documented"),
               "catalog_live_models_dir": str(t / "live"), "catalog_release_dir": str(t / "releases")}
        cfg.update(extra)
        return catalog.CatalogSettings.from_config(cfg, t / "Models", t / "raw")

    def production_state(self):
        return {str(p): hashlib.sha256(p.read_bytes()).hexdigest()
                for d in ("prod", "Models", "training", "documented", "live")
                for p in sorted((self.tmp / d).rglob("*")) if p.is_file()} | {
            str(self.tmp / "map.yaml"): hashlib.sha256((self.tmp / "map.yaml").read_bytes()).hexdigest()}

    def publish(self, reason="prvo izdanje"):
        return store.publish_release(self.settings, "Aleksa", "admin", reason)

    def identity(self, name):
        return next(v for v in catalog.list_articles(self.settings)["items"] if v["name"] == name)

    def decide(self, kind, name, **kw):
        v = self.identity(name)
        args = {"identity_id": v["identity_id"]} if kind == "classes" else {"article_id": v["article_id"]}
        return catalog.record_decision(self.settings, kind, "Aleksa", "admin", reason="test", **args, **kw)

    # ---- first release equals today's files ----

    def test_first_release_without_decisions_is_identical_to_todays_files(self):
        before = self.production_state()
        nxt = store.next_release(self.settings)
        self.assertEqual(nxt["baseline_label"], store.PRODUCTION_LABEL)
        self.assertTrue(nxt["parity"]["identical"], nxt["parity"]["items"])
        self.assertTrue(all(c["ok"] for c in nxt["checks"]), nxt["checks"])
        self.assertEqual(nxt["changes"], [])
        self.assertTrue(nxt["can_publish"])
        result = self.publish()
        self.assertEqual(result["number"], 1)
        folder = self.tmp / "releases" / "0001"
        self.assertEqual(yaml.safe_load((folder / R.MAP_FILE).read_text()), yaml.safe_load(PROD_MAP))
        black = [l for l in (folder / R.BLACKLIST_FILE).read_text().splitlines() if l and not l.startswith("#")]
        self.assertEqual(black, ["OMLET", "Skip Me"])
        self.assertEqual(yaml.safe_load((folder / "class_lists" / "Glasses.yaml").read_text())["names"],
                         ["CASA", "NISKA_BELO", "NISKA_ZUTO", "LEGACY_OLD"])
        self.assertEqual(yaml.safe_load((folder / "training_classes" / "glasses.yaml").read_text())["classes"]["exclude_prefixes"],
                         ["LEGACY_"])
        self.assertEqual(json.loads((folder / "RELEASE.json").read_text())["release"], 1)
        self.assertEqual((self.tmp / "releases" / "CURRENT").read_text().strip(), "1")
        self.assertEqual(self.production_state(), before)

    def test_every_difference_from_todays_files_is_explained_or_marked(self):
        (self.tmp / "documented" / "glasses.yaml").write_text(yaml.safe_dump({"model": "glasses", "excluded": []}), encoding="utf-8")
        (self.tmp / "prod" / "pos_to_internal_mapping.yaml").write_text(PROD_MAP + "\nHAND EDIT:\n- glasses.CASA\n", encoding="utf-8")
        self.decide("ignore", "NEW DRINK")
        parity = store.next_release(self.settings)["parity"]
        items = {i["text"]: i for i in parity["items"]}
        doc = next(i for i in parity["items"] if i["area"] == "documented")
        self.assertTrue(doc["explained"])
        self.assertTrue(any("nema spisak klasa" in d for d in doc["details"]))
        hand = next(i for t, i in items.items() if t.startswith("HAND EDIT"))
        self.assertFalse(hand["explained"])
        new = next(i for t, i in items.items() if t.startswith("NEW DRINK"))
        self.assertTrue(new["explained"])
        self.assertIn("odluka #", new["why"])
        self.assertEqual(parity["unexplained"], 1)

    # ---- checks ----

    def test_class_missing_in_live_model_blocks(self):
        self.write_live("shots", ["RED"])
        nxt = store.next_release(self.settings)
        check = next(c for c in nxt["checks"] if c["check"] == "classes")
        self.assertFalse(check["ok"])
        self.assertEqual(check["problems"], ["Rakija: Dunja: traži shots.AMBER, a te klase nema u živom modelu."])
        self.assertFalse(nxt["can_publish"])
        with self.assertRaises(store.ReleaseBlocked):
            self.publish()
        self.assertFalse((self.tmp / "releases").exists())
        self.assertEqual(store.list_releases(self.settings)["releases"], [])

    def test_lost_article_blocks(self):
        self.publish()
        self.write_map(drop="Niska")
        catalog.import_catalog(self.settings)
        check = next(c for c in store.next_release(self.settings)["checks"] if c["check"] == "lost")
        self.assertFalse(check["ok"])
        self.assertTrue(any(p.startswith("Niska:") for p in check["problems"]))
        with self.assertRaises(store.ReleaseBlocked):
            self.publish("drugo")

    def test_ignored_by_decision_is_not_lost(self):
        self.decide("ignore", "Casa Vina")
        nxt = store.next_release(self.settings)
        self.assertTrue(all(c["ok"] for c in nxt["checks"]), nxt["checks"])
        self.assertIn("Casa Vina: više se ne prati (ide na listu za ignorisanje).", [c["text"] for c in nxt["changes"]])

    def test_duplicate_codes_and_conflicting_decisions_block(self):
        variations = [R.VariationState(1, 10, "0100", "A", "tracked", [("glasses", "CASA")], []),
                      R.VariationState(2, 11, "0100", "B", "tracked", [("glasses", "CASA")], []),
                      R.VariationState(3, 12, "0300", "same", "ignored", [], [{"id": 1}]),
                      R.VariationState(4, 13, "0301", "SAME ", "tracked", [("glasses", "CASA")], [{"id": 2}])]
        src = R.ReleaseSources([], [], variations, {}, {})
        gen = R.generate(src)
        self.assertEqual(len(gen.conflicts), 1)
        content = R.parse_files(gen.files)
        checks = {c["check"]: c for c in R.run_checks(content, content, gen, src, {})}
        self.assertFalse(checks["duplicates"]["ok"])
        self.assertTrue(any("Šifra 0100" in p for p in checks["duplicates"]["problems"]))
        self.assertTrue(any("različite odluke" in p for p in checks["duplicates"]["problems"]))

    # ---- immutability ----

    def test_published_release_cannot_change(self):
        self.publish()
        conn = sqlite3.connect(str(self.tmp / "db" / "catalog.db"))
        with self.assertRaises(sqlite3.IntegrityError):
            conn.execute("UPDATE releases SET reason = 'x'")
        with self.assertRaises(sqlite3.IntegrityError):
            conn.execute("DELETE FROM releases")
        conn.close()
        folder = self.tmp / "releases" / "0001"
        self.assertFalse(os.access(folder / R.MAP_FILE, os.W_OK) and os.stat(folder / R.MAP_FILE).st_mode & 0o222)
        with self.assertRaises(catalog.CatalogError):
            self.publish("isto")  # nothing changed
        self.decide("ignore", "NEW DRINK")
        before = (folder / R.BLACKLIST_FILE).read_text()
        self.publish("drugo")
        self.assertEqual((folder / R.BLACKLIST_FILE).read_text(), before)  # release 1 kept as it was
        self.assertTrue(all(r["intact"] for r in store.list_releases(self.settings)["releases"]))

    def test_decision_after_publish_does_not_touch_old_release(self):
        self.publish()
        old = store.release_file(self.settings, 1, R.MAP_FILE)
        self.decide("classes", "NEW DRINK", payload={"links": [{"model": "glasses", "class": "CASA"}]})
        self.assertEqual(store.release_file(self.settings, 1, R.MAP_FILE), old)
        nxt = store.next_release(self.settings)
        self.assertEqual(nxt["baseline_label"], "važeće izdanje 1")
        self.assertIn("NEW DRINK: počinje da se prati kao glasses.CASA.", [c["text"] for c in nxt["changes"]])

    def test_waiting_tag_clears_after_publish(self):
        self.decide("ignore", "NEW DRINK")
        tags = lambda: next(i for i in catalog.list_unclassified(self.settings)["groups"] if i["state"] == "ignored")["items"]
        item = next(i for i in tags() if i["name"] == "NEW DRINK")
        self.assertIn("ručna odluka, čeka izdanje", item["tags"])
        self.publish()
        item = next(i for i in tags() if i["name"] == "NEW DRINK")
        self.assertNotIn("ručna odluka, čeka izdanje", item["tags"])

    # ---- rollback ----

    def test_rollback_gives_identical_files_and_is_recorded(self):
        before = self.production_state()
        self.publish()
        self.decide("ignore", "NEW DRINK")
        self.publish("NEW DRINK ne pratimo")
        result = store.rollback_release(self.settings, 1, "Aleksa", "admin", "greška")
        self.assertEqual((result["number"], result["kind"], result["based_on"]), (3, "rollback", 1))
        one, three = self.tmp / "releases" / "0001", self.tmp / "releases" / "0003"
        files = sorted(p.relative_to(one) for p in one.rglob("*") if p.is_file() and p.name != "RELEASE.json")
        self.assertEqual(files, sorted(p.relative_to(three) for p in three.rglob("*") if p.is_file() and p.name != "RELEASE.json"))
        for f in files:
            self.assertEqual((one / f).read_bytes(), (three / f).read_bytes())
        listed = store.list_releases(self.settings)["releases"]
        self.assertEqual([(r["number"], r["kind"], r["live"]) for r in listed],
                         [(3, "rollback", True), (2, "publish", False), (1, "publish", False)])
        self.assertEqual((self.tmp / "releases" / "CURRENT").read_text().strip(), "3")
        with self.assertRaises(catalog.CatalogError):
            store.rollback_release(self.settings, 1, "Aleksa", "admin", "opet")  # already live
        self.assertEqual(self.production_state(), before)

    def test_rollback_blocked_when_class_left_the_live_model(self):
        self.publish()
        self.decide("ignore", "NEW DRINK")
        self.publish("drugo")
        self.write_live("shots", ["RED"])
        with self.assertRaises(store.ReleaseBlocked):
            store.rollback_release(self.settings, 1, "Aleksa", "admin", "nazad")

    def test_sixth_version_database_is_upgraded_and_needs_one_import(self):
        db = self.tmp / "db6" / "catalog.db"
        db.parent.mkdir()
        conn = sqlite3.connect(str(db))
        conn.executescript(store._SCHEMA + store._SCHEMA_V2 + store._SCHEMA_V3 + store._SCHEMA_V4 + store._SCHEMA_V5
                           + store._SCHEMA_V6 + "PRAGMA user_version = 6;")
        conn.close()
        settings = self.make_settings(catalog_db_path=str(db), catalog_release_dir=str(self.tmp / "rel6"))
        catalog.import_catalog(settings)
        self.assertEqual(sqlite3.connect(str(db)).execute("PRAGMA user_version").fetchone()[0], store.SCHEMA_VERSION)
        self.assertTrue(store.next_release(settings)["parity"]["identical"])
        # A map imported before version 7 has no names as written: the release asks for one import instead of guessing.
        conn = sqlite3.connect(str(db))
        conn.execute("DELETE FROM map_names")
        conn.commit()
        conn.close()
        with self.assertRaises(catalog.CatalogError):
            store.next_release(settings)

    # ---- admin only, via the API ----

    def routes(self):
        t = self.tmp
        cfg = {"data_root": str(t / "data"), "catalog_venue_id": "venue_a", "catalog_db_path": str(t / "db" / "catalog.db"),
               "models_dir": str(t / "Models"), "raw_review_dir": str(t / "rr"), "relabel_batches_dir": str(t / "rb"),
               "catalog_blacklist_path": str(t / "prod" / "blacklist_items.txt"),
               "catalog_pipeline_map_path": str(t / "prod" / "pos_to_internal_mapping.yaml"),
               "catalog_training_config_dir": str(t / "training"), "catalog_documented_classes_dir": str(t / "documented"),
               "catalog_live_models_dir": str(t / "live"), "catalog_release_dir": str(t / "releases")}
        path = t / "labeler_config.json"
        path.write_text(json.dumps(cfg))
        old = os.environ.get("LABELER_CONFIG_PATH")
        os.environ["LABELER_CONFIG_PATH"] = str(path)
        try:
            app = server.create_app()
        finally:
            if old is None:
                os.environ.pop("LABELER_CONFIG_PATH", None)
            else:
                os.environ["LABELER_CONFIG_PATH"] = old
        return {(r.path, m): r.endpoint for r in app.routes for m in getattr(r, "methods", ())}

    def test_only_admin_publishes_and_rolls_back(self):
        from fastapi import HTTPException
        routes = self.routes()
        self.assertTrue(routes[("/api/catalog/releases/next", "GET")]()["can_publish"])
        with self.assertRaises(HTTPException) as e:
            routes[("/api/catalog/releases", "POST")]({"actor": "Goca", "role": "labeler", "reason": "probam"})
        self.assertEqual(e.exception.status_code, 403)
        with self.assertRaises(HTTPException) as e:
            routes[("/api/catalog/releases", "POST")]({"actor": "Aleksa", "role": "admin", "reason": " "})
        self.assertEqual(e.exception.status_code, 400)
        self.assertEqual(routes[("/api/catalog/releases", "POST")]({"actor": "Aleksa", "role": "admin", "reason": "prvo"})["number"], 1)
        self.decide("ignore", "NEW DRINK")
        routes[("/api/catalog/releases", "POST")]({"actor": "Aleksa", "role": "admin", "reason": "drugo"})
        with self.assertRaises(HTTPException) as e:
            routes[("/api/catalog/releases/{number}/rollback", "POST")](1, {"actor": "Goca", "role": "labeler", "reason": "x"})
        self.assertEqual(e.exception.status_code, 403)
        listed = routes[("/api/catalog/releases", "GET")]()
        self.assertEqual(listed["live_number"], 2)
        text = routes[("/api/catalog/releases/{number}/files/{path:path}", "GET")](2, R.BLACKLIST_FILE).body.decode()
        self.assertIn("NEW DRINK", text)
        self.write_live("shots", ["RED"])
        with self.assertRaises(HTTPException) as e:
            routes[("/api/catalog/releases/{number}/rollback", "POST")](1, {"actor": "Aleksa", "role": "admin", "reason": "x"})
        self.assertEqual(e.exception.status_code, 409)
        self.assertFalse(e.exception.detail["checks"][0]["ok"])


